// Dependencies
import { getValueFromDataKey } from "@arkitektum/altinn-studio-custom-components-utils";

// Global functions
import { fetchWithTimeoutAndClientLogger } from "./clientLoggerHelpers.ts";

/**
 * Form data a component reads from the app itself, rather than through the data model bindings the app frontend hands
 * it.
 *
 * A component asks for it by naming a data type in its layout, `"dataType": "DispensasjonssoeknadDataV1"`, and gets
 * the form data of that type's data element. A layout component reads the whole of it, so its layout needs no
 * bindings. A data component names the value it shows with `dataKey`, a path from the root of the data model.
 *
 * Only pages generated by app backend v9 are served. That frontend holds back the page's readiness for print while any
 * element carries `data-loading`, which is what lets a component fetch its data and still be in the PDF.
 */

/** What a component asking for form data from the app is told. */
export type AppFormDataState =
    /** The component did not ask, or the page is not one this serves. Draw from the frontend's data as before. */
    | { status: "none" }
    /** The data is on its way. Wait, and draw again when told. */
    | { status: "pending" }
    /** The form data, ready to draw from. */
    | { status: "ready"; formData: unknown }
    /** The data element could not be found or fetched. Draw from the frontend's data as before. */
    | { status: "unavailable" };

/** Where on the page the instance is, read from its address. */
export interface InstanceRoute {
    /** The app's own address, such as `https://dibk.apps.altinn.no/dibk/et-v4`. */
    appPath: string;
    /** `{partyId}/{instanceGuid}`, as the app API takes it. */
    instanceId: string;
    /** The subform entry the page shows, when it shows one. */
    dataElementId?: string;
}

/** The part of a data element this reads: which one it is and what type its data has. */
interface DataElement {
    id: string;
    dataType: string;
}

type Settled = { status: "ready"; formData: unknown } | { status: "unavailable" };

const GUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const FETCH_TIMEOUT_MS = 10000;

/**
 * Reads the instance from the address of a page the v9 frontend shows.
 *
 * The frontend routes by path: `/{org}/{app}/instance/{partyId}/{instanceGuid}/{taskId}/{page}`, and a subform entry
 * adds `/{componentId}/{dataElementId}/{page}`. A subform entry's PDF names its data element in the
 * `subformDataElementId` search parameter instead.
 *
 * @param location - The page's address.
 * @returns The instance and the subform entry the page shows, or null when the page shows no instance.
 */
export function getInstanceRoute(location: Pick<Location, "origin" | "pathname" | "search">): InstanceRoute | null {
    const [, org, app, instanceSegment, partyId, instanceGuid, , , , dataElementIdInPath] = location.pathname.split("/");
    if (!org || !app || instanceSegment !== "instance" || !partyId || !GUID_PATTERN.test(instanceGuid ?? "")) {
        return null;
    }
    const dataElementIdInSearch = new URLSearchParams(location.search).get("subformDataElementId");
    const dataElementId = [dataElementIdInSearch, dataElementIdInPath].find((id) => !!id && GUID_PATTERN.test(id));
    return {
        appPath: `${location.origin}/${org}/${app}`,
        instanceId: `${partyId}/${instanceGuid}`,
        ...(dataElementId ? { dataElementId } : {})
    };
}

/**
 * Picks the data element a component naming a data type reads.
 *
 * The subform entry the page shows wins when it has that type. Otherwise the instance must have exactly one element of
 * the type: with several, as when a summary lists every entry of a subform, the address does not say which one the
 * component is showing, and guessing would show one entry's data under another.
 *
 * @param dataElements - The instance's data elements.
 * @param dataType - The data type the component names.
 * @param shownDataElementId - The subform entry the page shows, if any.
 * @returns The id of the data element, or undefined when it cannot be told.
 */
export function pickDataElementId(dataElements: DataElement[], dataType: string, shownDataElementId?: string): string | undefined {
    const ofType = dataElements.filter((dataElement) => dataElement?.dataType === dataType);
    if (shownDataElementId && ofType.some((dataElement) => dataElement.id === shownDataElementId)) {
        return shownDataElementId;
    }
    return ofType.length === 1 ? ofType[0]!.id : undefined;
}

/**
 * What a component draws from: the whole form data, or the value at `dataKey` as `formData.data`, which is where
 * getComponentDataValue looks.
 *
 * @param data - The form data of the data element.
 * @param dataKey - The path to the value the component shows, if it names one.
 * @returns The form data to hand the component.
 */
export function getFormDataForComponent(data: unknown, dataKey?: string | null): unknown {
    return dataKey ? { data: getValueFromDataKey(data, dataKey) } : data;
}

/**
 * The form data fetched for the current page, by data type. Thrown away when the page changes, since the frontend
 * saves before it navigates, so the next page reads what the user last entered.
 */
let cache: {
    pageKey: string;
    dataElements: Promise<DataElement[] | null> | null;
    byDataType: Map<string, { settled?: Settled; waiting: Map<object, () => void> }>;
} | null = null;

/** Forgets everything fetched. For tests. */
export function resetAppFormDataCache(): void {
    cache = null;
}

function logError(message: string): void {
    globalThis.clientLogger?.postLogData([{ level: "Error", message }]);
    console.error(message);
}

/**
 * Fetches JSON from the app API, logging a failure and answering null. Only the address and the status are logged,
 * never what came back, as the form data can hold personal data.
 */
async function fetchJson(url: string): Promise<unknown> {
    try {
        const response = await fetchWithTimeoutAndClientLogger(
            url,
            { headers: { Accept: "application/json" } },
            FETCH_TIMEOUT_MS,
            globalThis.clientLogger ?? null
        );
        if (!response?.ok) {
            logError(`Could not fetch ${url}. HTTP status: ${response?.status}`);
            return null;
        }
        return await response.json();
    } catch (error) {
        logError(`Could not fetch ${url}. Error: ${(error as Error)?.name}`);
        return null;
    }
}

async function loadDataElements(route: InstanceRoute): Promise<DataElement[] | null> {
    const instance = (await fetchJson(`${route.appPath}/instances/${route.instanceId}`)) as { data?: DataElement[] } | null;
    return Array.isArray(instance?.data) ? instance.data : null;
}

async function loadFormData(route: InstanceRoute, dataElements: Promise<DataElement[] | null>, dataType: string): Promise<Settled> {
    const dataElementId = pickDataElementId((await dataElements) ?? [], dataType, route.dataElementId);
    if (!dataElementId) {
        return { status: "unavailable" };
    }
    const data = await fetchJson(`${route.appPath}/instances/${route.instanceId}/data/${dataElementId}`);
    return data === null ? { status: "unavailable" } : { status: "ready", formData: data };
}

/**
 * The form data of a data type for the current page, fetching it on first ask.
 *
 * While it is on its way the answer is "pending", and `onSettled` is called once it has arrived or failed. Asking again
 * with the same `waiter` before then replaces its callback rather than adding another, so a component drawn several
 * times while waiting is drawn once more, not once per ask.
 *
 * @param dataType - The data type the component names.
 * @param waiter - Who is asking, typically the component's element.
 * @param onSettled - Called once the data has arrived or failed, if it was not there yet.
 * @returns Whether the data is ready, on its way, or not to be had.
 */
export function requestAppFormData(dataType: string, waiter: object, onSettled: () => void): AppFormDataState {
    const route = getInstanceRoute(globalThis.location);
    if (!route) {
        return { status: "unavailable" };
    }
    const pageKey = `${globalThis.location.pathname}${globalThis.location.search}`;
    if (cache?.pageKey !== pageKey) {
        cache = { pageKey, dataElements: null, byDataType: new Map() };
    }
    const current = cache;
    let entry = current.byDataType.get(dataType);
    if (!entry) {
        entry = { waiting: new Map() };
        current.byDataType.set(dataType, entry);
        current.dataElements ??= loadDataElements(route);
        const settling = entry;
        void loadFormData(route, current.dataElements, dataType).then((settled) => {
            settling.settled = settled;
            const waiting = [...settling.waiting.values()];
            settling.waiting.clear();
            waiting.forEach((callback) => callback());
        });
    }
    if (entry.settled) {
        return entry.settled;
    }
    entry.waiting.set(waiter, onSettled);
    return { status: "pending" };
}

/**
 * What an element asking for form data from the app is told, read off the `datatype` and `datakey` attributes the
 * frontend writes from its layout.
 *
 * @param host - The custom element.
 * @param onSettled - Called once the data has arrived or failed, if it was not there yet.
 * @returns The state, with the form data shaped for the component once it is ready.
 */
export function getAppFormDataForElement(host: HTMLElement, onSettled: () => void): AppFormDataState {
    const dataType = host?.getAttribute?.("dataType");
    if (!dataType || typeof globalThis.altinnAppGlobalData === "undefined") {
        return { status: "none" };
    }
    const state = requestAppFormData(dataType, host, onSettled);
    return state.status === "ready" ? { status: "ready", formData: getFormDataForComponent(state.formData, host.getAttribute("dataKey")) } : state;
}
