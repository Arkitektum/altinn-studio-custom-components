/**
 * Loads a script asynchronously by creating a script element and appending it to the document body.
 *
 * @param src - The source URL of the script to load.
 * @param clientLogger - Optional client logger instance for logging errors.
 * @param clientLoggerCustomFields - Optional custom fields for the client logger.
 * @returns A promise that resolves with the script element when the script is loaded, or rejects with an error if the script fails to load.
 */
function loadScriptAsync(
    src: string,
    clientLogger: ClientLogger | null = null,
    clientLoggerCustomFields: LogCustomField[] = []
): Promise<HTMLScriptElement> {
    return new Promise((resolve, reject) => {
        const script = document.createElement("script");
        script.src = src;
        script.onload = () => {
            console.log(`${src} loaded`);
            resolve(script);
        };
        script.onerror = () => {
            clientLogger?.postLogData([
                {
                    level: "Error",
                    message: `Script load error for ${src}`,
                    custom_fields: clientLoggerCustomFields
                }
            ]);
            reject(new Error(`Script load error for ${src}`));
        };
        document.body.appendChild(script);
    });
}

/**
 * Whether an origin is one an Altinn app is served from: an app host on Altinn's production or tt02 environment, or
 * LocalTest. Every app is served from its org's own subdomain, so the check is on the domain rather than a list of orgs.
 *
 * The path cannot answer this on its own: any page with two path segments looks like `/{org}/{app}/`, so a page that
 * only uses the components (the docs site's `/altinn-studio-custom-components-docs/index.html`, for one) would
 * otherwise be booted as an app, loading the Altinn frontend from the CDN and posting to the client logger.
 *
 * @param origin - The origin to check, such as `https://dibk.apps.altinn.no`.
 * @returns True when an Altinn app can be served from the origin.
 */
export function isAltinnAppOrigin(origin: string): boolean {
    let url: URL;
    try {
        url = new URL(origin);
    } catch {
        return false;
    }
    if (url.hostname === "local.altinn.cloud") {
        return url.protocol === "http:" || url.protocol === "https:";
    }
    return url.protocol === "https:" && (url.hostname.endsWith(".apps.altinn.no") || url.hostname.endsWith(".apps.tt02.altinn.no"));
}

/**
 * Whether the page already carries the Altinn app frontend.
 *
 * From app backend v9 the app generates the index page itself: it loads the frontend that ships with the backend and
 * puts the app's global data on `altinnAppGlobalData` before any script runs. The CDN frontend must not be loaded on
 * top of it, as the v8 frontend calls endpoints the v9 backend does not have.
 *
 * @returns True when the page was generated by app backend v9 or later.
 */
function hasBundledAppFrontend(): boolean {
    return typeof globalThis.altinnAppGlobalData !== "undefined";
}

/**
 * Holds the browser's own DOMContentLoaded back from the bundled app frontend.
 *
 * The bundled frontend renders on DOMContentLoaded, and the components need their text resources on the global scope
 * before it does. The listener runs in the capture phase on the window, ahead of the frontend's listener on the
 * document, and stops only the trusted event. The synthetic DOMContentLoaded that init dispatches once the text
 * resources are ready is untrusted, so it goes through, the same way it boots the CDN frontend.
 *
 * Nothing is held if the page has already loaded, since the frontend has booted by then.
 */
function holdNativeDomContentLoaded(): void {
    if (document.readyState !== "loading") {
        return;
    }
    const hold = (event: Event) => {
        if (event.isTrusted) {
            event.stopImmediatePropagation();
            globalThis.removeEventListener("DOMContentLoaded", hold, { capture: true });
        }
    };
    globalThis.addEventListener("DOMContentLoaded", hold, { capture: true });
}

/**
 * Reads the instance id, `{partyId}/{instanceGuid}`, from where the page is.
 *
 * App frontend v4 carries it in the hash (`#/instance/{partyId}/{instanceGuid}/...`), v9 in the path.
 *
 * @param location - Where the page is.
 * @returns The instance id, or undefined on a page that shows no instance.
 */
function getInstanceIdFromLocation(location: Location): string | undefined {
    const [, segment, partyId, instanceGuid] = location?.hash?.split("?")[0]?.split("/") ?? [];
    if (segment === "instance" && partyId && instanceGuid) {
        return `${partyId}/${instanceGuid}`;
    }
    return getInstanceRoute(location)?.instanceId;
}

/**
 * Reads the language the page was asked for in its address, which overrides the one in the user's profile.
 *
 * Altinn's endpoints take the language as `language` or `lang` (`pdf/preview?lang=nn`, `process/next?lang=nb`), and
 * when they render a pdf they open the frontend with it as `lang`: in the hash for app frontend v4
 * (`#/instance/{partyId}/{instanceGuid}?pdf=1&lang=nn`), in the query for v9. Both are read, `language` before `lang`
 * as Altinn reads them. Only a two or three letter code is taken, since it goes into the text resource address.
 *
 * @param location - Where the page is.
 * @returns The language in lower case, or null when the address names none.
 */
export function getLanguageFromLocation(location: Location): string | null {
    const hashQuery = location?.hash?.split("?").slice(1).join("?") ?? "";
    for (const query of [new URLSearchParams(location?.search ?? ""), new URLSearchParams(hashQuery)]) {
        const language = query.get("language") ?? query.get("lang");
        if (language !== null && /^[a-z]{2,3}$/i.test(language)) {
            return language.toLowerCase();
        }
    }
    return null;
}

/**
 * What init needs from the user's Altinn profile.
 */
interface UserProfile {
    /** The language the user prefers, or null when the profile names none. */
    language: string | null;
    /** The user's id, which app frontend keys the language picker's choice on. */
    userId: number | string | undefined;
}

/**
 * Posts an error to the client logger and the console.
 *
 * @param message - What went wrong.
 * @param clientLogger - The client logger instance.
 * @param clientLoggerCustomFields - Custom fields to include in the client logger.
 */
function logInitError(message: string, clientLogger: ClientLogger | null, clientLoggerCustomFields: LogCustomField[]): void {
    clientLogger?.postLogData([
        {
            level: "Error",
            message,
            custom_fields: clientLoggerCustomFields
        }
    ]);
    console.error(message);
}

/**
 * Fetches the user's preferred language and user id from the Altinn profile API.
 *
 * This function never throws. Any failure (network error, timeout, non-OK response such as HTTP 500,
 * or an unparsable response body) is logged and results in `null`, and a missing language preference is logged
 * and results in a null `language`, so the caller can fall back to the default language instead of leaving the
 * app unrendered.
 *
 * @async
 * @param origin - The origin URL of the app.
 * @param org - The organization identifier.
 * @param app - The application identifier.
 * @param clientLogger - The client logger instance.
 * @param clientLoggerCustomFields - Custom fields to include in the client logger.
 * @returns The user's language preference and user id, or null if the profile could not be read.
 */
async function fetchUserProfile(
    origin: string,
    org: string,
    app: string,
    clientLogger: ClientLogger | null,
    clientLoggerCustomFields: LogCustomField[]
): Promise<UserProfile | null> {
    const userProfileApiUrl = `${origin}/${org}/${app}/api/v1/profile/user`;
    const logError = (message: string) => logInitError(message, clientLogger, clientLoggerCustomFields);

    let userProfileResponse;
    try {
        userProfileResponse = await fetchWithTimeoutAndClientLogger(userProfileApiUrl, {}, 5000, clientLogger, clientLoggerCustomFields);
    } catch (error) {
        logError(`Failed to fetch user profile data from ${userProfileApiUrl}. Error: ${(error as Error)?.message}`);
        return null;
    }

    if (!userProfileResponse?.ok) {
        logError(
            `Failed to fetch user profile data from ${userProfileApiUrl}. ` +
                `HTTP status: ${userProfileResponse?.status} (${userProfileResponse?.statusText})`
        );
        return null;
    }

    let userProfileData;
    try {
        userProfileData = await userProfileResponse.json();
    } catch (error) {
        logError(`Could not parse user profile data from ${userProfileApiUrl}. Error: ${(error as Error)?.message}`);
        return null;
    }

    const language = userProfileData?.profileSettingPreference?.language;
    if (!language) {
        logError("Could not determine the user's language preference.");
    }

    return { language: language || null, userId: userProfileData?.userId };
}

/**
 * Fetches the languages the app has texts for: one `resource.<language>.json` in its `App/config/texts` each.
 *
 * This is what app frontend offers in its language picker and the only languages it will show the app in, so the
 * components keep to the same list. An app that has only an nb resource file is shown in nb to every reader, even
 * though this package ships its own texts in nn and en too.
 *
 * This function never throws. Any failure is logged and results in `null`, and so does an empty list, as a list
 * that cannot be chosen from tells nothing.
 *
 * @async
 * @param origin - The origin URL of the app.
 * @param org - The organization identifier.
 * @param app - The application identifier.
 * @param clientLogger - The client logger instance.
 * @param clientLoggerCustomFields - Custom fields to include in the client logger.
 * @returns The app's language codes, or null when they could not be determined.
 */
async function fetchAppLanguages(
    origin: string,
    org: string,
    app: string,
    clientLogger: ClientLogger | null,
    clientLoggerCustomFields: LogCustomField[]
): Promise<string[] | null> {
    const appLanguagesApiUrl = `${origin}/${org}/${app}/api/v1/applicationlanguages`;
    const logError = (message: string) => logInitError(message, clientLogger, clientLoggerCustomFields);

    let appLanguagesResponse;
    try {
        appLanguagesResponse = await fetchWithTimeoutAndClientLogger(appLanguagesApiUrl, {}, 5000, clientLogger, clientLoggerCustomFields);
    } catch (error) {
        logError(`Failed to fetch the app's languages from ${appLanguagesApiUrl}. Error: ${(error as Error)?.message}`);
        return null;
    }

    if (!appLanguagesResponse?.ok) {
        logError(
            `Failed to fetch the app's languages from ${appLanguagesApiUrl}. ` +
                `HTTP status: ${appLanguagesResponse?.status} (${appLanguagesResponse?.statusText})`
        );
        return null;
    }

    let appLanguagesData;
    try {
        appLanguagesData = await appLanguagesResponse.json();
    } catch (error) {
        logError(`Could not parse the app's languages from ${appLanguagesApiUrl}. Error: ${(error as Error)?.message}`);
        return null;
    }

    const languages = Array.isArray(appLanguagesData)
        ? appLanguagesData.map((entry) => entry?.language).filter((language): language is string => typeof language === "string" && language !== "")
        : [];
    if (languages.length === 0) {
        logError(`Could not determine the app's languages from ${appLanguagesApiUrl}.`);
        return null;
    }

    return languages;
}

/**
 * Reads the language the user last chose in app frontend's language picker for this app.
 *
 * App frontend keeps it in local storage under `{org}/{app}/{userId}/selectedLanguage`, as a JSON string, and has
 * done so since at least v4.20. Only a two or three letter code is taken, since it goes into the text resource address.
 * Local storage can be unreadable (blocked by the browser, or a value that is not JSON), which reads as no choice.
 *
 * @param org - The organization identifier.
 * @param app - The application identifier.
 * @param userId - The user's id from the profile. App frontend leaves it out of the key when there is none.
 * @returns The chosen language in lower case, or null when there is none.
 */
export function getLanguageFromSelector(org: string, app: string, userId: number | string | undefined): string | null {
    const scope = [org, app, userId].filter((part) => part !== undefined && part !== null && part !== "");
    try {
        const stored = globalThis.localStorage?.getItem(`${scope.join("/")}/selectedLanguage`);
        const language = stored ? JSON.parse(stored) : null;
        return typeof language === "string" && /^[a-z]{2,3}$/i.test(language) ? language.toLowerCase() : null;
    } catch {
        return null;
    }
}

/**
 * Picks the language to show, the way app frontend does: the first of the reader's wishes the app has texts for, else
 * nb, nn or en if the app has one of them, else the app's first language.
 *
 * When the app's languages are unknown, the reader's first wish is taken as it is, and nb when there is none.
 *
 * @param appLanguages - The languages the app has texts for, or null when they are unknown.
 * @param wishes - The reader's wishes, most important first. Missing ones are skipped.
 * @returns The language to show.
 */
export function resolveLanguage(appLanguages: readonly string[] | null, wishes: readonly (string | null | undefined)[]): string {
    const given = wishes.filter((wish): wish is string => typeof wish === "string" && wish !== "");
    if (appLanguages === null) {
        return given[0] ?? "nb";
    }
    const supported = [...given, "nb", "nn", "en"].find((language) => appLanguages.includes(language));
    return supported ?? (appLanguages[0] as string);
}

/**
 * Initializes custom components by determining the language (from the address, else the language picker or the user profile, kept to the app's languages), loading text resources, and dispatching a DOMContentLoaded event.
 * This function is intended to be called once when the application starts to set up the necessary environment for custom components to function correctly.
 *
 * Failures while determining the user's language or loading text resources are logged and do not abort initialization;
 * the app frontend is loaded with the fallback language ("nb") instead.
 *
 * @async
 * @returns {Promise<void>} A promise that resolves when initialization is complete.
 * @throws {Error} Throws an error if the app frontend script could not be loaded.
 */
export default async function initCustomComponents() {
    // Anywhere but an Altinn app the components are only being rendered, so there is no app to boot and nothing to log.
    if (!isAltinnAppOrigin(globalThis.location.origin)) {
        console.info("Not served from an Altinn app origin, so the Altinn app frontend is not loaded.");
        return;
    }

    const appId = globalThis.location.pathname.split("/");
    const instanceId = getInstanceIdFromLocation(globalThis.location);
    const origin = globalThis.location.origin;
    const org = appId?.[1];
    const app = appId?.[2];
    const altinnAppFrontendVersionFallback = "4.29.0";
    const altinnAppFrontendVersion =
        (document.querySelector("meta[data-altinn-app-frontend-version]") as HTMLMetaElement | null)?.dataset?.altinnAppFrontendVersion ||
        altinnAppFrontendVersionFallback;

    let clientLogger = null;
    try {
        clientLogger = getClientLoggerInstance();
    } catch (error) {
        console.error("Could not create the client logger instance.", error);
    }
    globalThis.clientLogger = clientLogger;
    // Both are parsed out of the URL and either can come back missing. The logger takes that in its stride, so
    // they are carried as they are rather than being filled in with something that was never true.
    const clientLoggerCustomFields = [
        { key: "instanceId", value: instanceId },
        { key: "app", value: app }
    ] as LogCustomField[];

    if (!origin || !org || !app) {
        console.error("Could not determine the origin, organization, or application from the URL.");
        return;
    }

    // Must happen before the first await, while the page is still loading. Nothing below throws before the
    // synthetic DOMContentLoaded is dispatched, so the frontend is never held back for good.
    const bundledAppFrontend = hasBundledAppFrontend();
    if (bundledAppFrontend) {
        holdNativeDomContentLoaded();
    }

    const fallbackLanguage = "nb";
    let selectedLanguage = fallbackLanguage;
    let textResources = null;
    let defaultTextResources = null;
    let fallbackTextResources = null;
    let fallbackDefaultTextResources = null;

    try {
        updateBodyClassNamesForApplication(org, app);

        // A language in the address is what the page was asked for, so the profile is not asked at all. Otherwise the
        // choice made in app frontend's language picker comes before the profile's, as it does in app frontend.
        // Either way it is only taken if the app has texts in it, so the components show the language the app is shown in.
        const addressLanguage = getLanguageFromLocation(globalThis.location);
        const [userProfile, appLanguages] = await Promise.all([
            addressLanguage ? null : fetchUserProfile(origin, org, app, clientLogger, clientLoggerCustomFields),
            fetchAppLanguages(origin, org, app, clientLogger, clientLoggerCustomFields)
        ]);
        selectedLanguage = resolveLanguage(appLanguages, [
            addressLanguage,
            userProfile ? getLanguageFromSelector(org, app, userProfile.userId) : null,
            userProfile?.language
        ]);

        // A reader in another language than nb also gets the nb texts, the app's and the package's, for a text missing
        // from those in their language: the components look there before showing a text's id.
        // A failed nb request leaves those texts out, and never costs the reader the texts in their own language.
        const readsFallbackLanguage = selectedLanguage === fallbackLanguage;
        const orNothing = (request: Promise<unknown>) => request.catch(() => null);
        [textResources, defaultTextResources, fallbackTextResources, fallbackDefaultTextResources] = await Promise.all([
            fetchTextResources(origin, org, app, selectedLanguage, fallbackLanguage, clientLogger, clientLoggerCustomFields),
            fetchDefaultTextResources(origin, org, app, selectedLanguage, fallbackLanguage, clientLogger, clientLoggerCustomFields),
            readsFallbackLanguage
                ? null
                : orNothing(fetchTextResources(origin, org, app, fallbackLanguage, null, clientLogger, clientLoggerCustomFields)),
            // The package's texts are already nb for a language it ships no file for, so they are not asked for twice.
            readsFallbackLanguage || !defaultTextResourceLanguages.includes(selectedLanguage)
                ? null
                : orNothing(fetchDefaultTextResources(origin, org, app, fallbackLanguage, null, clientLogger, clientLoggerCustomFields))
        ]);
    } catch (error) {
        // Language and text resource problems must never prevent the app frontend from being loaded,
        // as that would leave the user with a blank page. Log and continue with what we have.
        clientLogger?.postLogData([
            {
                level: "Error",
                message: `Failed to prepare text resources for language '${selectedLanguage}'. Error: ${(error as Error)?.message}`,
                custom_fields: clientLoggerCustomFields
            }
        ]);
        console.error(`Failed to prepare text resources for language '${selectedLanguage}'.`, error);
    }

    globalThis.selectedLanguage = selectedLanguage;
    globalThis.textResources = textResources;
    globalThis.defaultTextResources = defaultTextResources;
    globalThis.fallbackTextResources = fallbackTextResources;
    globalThis.fallbackDefaultTextResources = fallbackDefaultTextResources;

    if (!bundledAppFrontend) {
        await loadScriptAsync(
            `https://altinncdn.no/toolkits/altinn-app-frontend/${altinnAppFrontendVersion}/altinn-app-frontend.js`,
            clientLogger,
            clientLoggerCustomFields
        );
    }

    const domContentLoadedEvent = new Event("DOMContentLoaded", {
        bubbles: true, // Event bubbles up through the DOM
        cancelable: false // The native event is not cancelable
    });

    document.dispatchEvent(domContentLoadedEvent);
}
